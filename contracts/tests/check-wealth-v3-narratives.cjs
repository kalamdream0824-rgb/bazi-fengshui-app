// Validates generated Content, never invents a ready report id or asserts that saving/reading is enabled.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const { createRequire } = require('node:module')
const requireWeb = createRequire(resolve(__dirname, '../../apps/web/package.json'))
const Ajv = requireWeb('ajv')
const schema = JSON.parse(readFileSync(resolve(__dirname, '../drafts/wealth-v3.schema.json'), 'utf8'))
assert.ok(process.argv[2], 'Pass target/wealth-v3-narratives.json generated by WealthNarrativeSampleTest')
const data = JSON.parse(readFileSync(resolve(process.argv[2]), 'utf8'))
assert.equal(data.scope, 'internal-narrative-review-not-a-saved-report')
assert.equal(data.cases.length, 22)
assert.ok(data.rejectedCases.some(s => s.startsWith('S01:')))
const ajv = new Ajv({ allErrors: true, schemaId: 'auto' }).addSchema(schema)
const validate = ajv.compile({ $ref: `${schema.$id}#/definitions/Content` })
let publicShapes = 0
let internalShapes = 0
let maxProductBytes = 0
for (const sample of data.cases) {
  const c = sample.content
  assert.equal(c.years.length, c.horizonYears)
  if (c.horizonYears === 3) {
    assert.ok(validate(c), `${sample.id}: ${JSON.stringify(validate.errors)}`)
    publicShapes++
    maxProductBytes = Math.max(maxProductBytes, Buffer.byteLength(JSON.stringify(c), 'utf8'))
  } else {
    assert.ok([2, 5].includes(c.horizonYears))
    assert.equal(validate(c), false, 'Internal two/five-year drafts are not public product responses')
    internalShapes++
  }
  const decisions = new Map(c.years.flatMap(y => y.decisions).map(d => [d.id, d]))
  const blocks = [c.thesis, c.summary, ...c.pathSummaries.map(p => p.reading), c.riskSummary,
    ...c.years.flatMap(y => [y.overview, ...y.income, y.retention, y.risk?.reading,
      ...y.observations, ...y.actions, y.comparison?.reading]), ...c.route, c.readingNote].filter(Boolean)
  assert.equal(new Set(blocks.map(b => b.id)).size, blocks.length)
  for (const b of blocks) {
    assert.ok(b.text.length > 0 && b.text.length <= 240)
    assert.equal(new Set(b.years).size, b.years.length)
    b.years.forEach(year => assert.ok(c.years.some(y => y.year === year)))
    b.decisionIds.forEach(id => assert.ok(decisions.has(id) && b.years.includes(decisions.get(id).year)))
    if (b.kind === 'interpretation') assert.ok(b.decisionIds.some(id => decisions.get(id).stance !== 'quiet'))
  }
  c.years.forEach((y, index) => {
    assert.equal(y.year, Number(c.asOf.slice(0, 4)) + index)
    const own = [y.overview, ...y.income, y.retention, y.risk?.reading, ...y.observations, ...y.actions].filter(Boolean)
    own.forEach(b => assert.deepEqual(b.years, [y.year]))
    y.actions.forEach(b => assert.equal(b.kind, 'general_advice'))
    y.observations.forEach(b => assert.equal(b.kind, 'observation'))
    if (y.risk) {
      assert.deepEqual(new Set(y.risk.limitingEvidenceIds),
        new Set(y.evidence.filter(e => e.path === y.risk.path && e.weight < 0).map(e => e.id)))
      assert.ok(y.risk.limitingEvidenceIds.length > 0)
    } else assert.ok(y.decisions.every(d => d.limitationWeight === 0))
    if (index === c.years.length - 1) assert.equal(y.comparison, null)
    else {
      const next = c.years[index + 1]
      assert.deepEqual(y.comparison.reading.years, [y.year, next.year])
      assert.equal(y.comparison.toYear, next.year)
      y.comparison.changes.forEach(change => {
        change.addedEvidenceIds.forEach(id => assert.ok(next.evidence.some(e => e.id === id && e.path === change.path)))
        change.removedEvidenceIds.forEach(id => assert.ok(y.evidence.some(e => e.id === id && e.path === change.path)))
      })
    }
  })
  const riskYears = c.years.filter(y => y.risk).map(y => y.year)
  if (riskYears.length) assert.deepEqual(c.riskSummary.years, riskYears)
  else assert.equal(c.riskSummary, null)
  c.pathSummaries.forEach(p => assert.deepEqual(p.yearDecisionIds,
    c.years.map(y => y.decisions.find(d => d.path === p.path).id)))
}
assert.equal(publicShapes, 20)
assert.equal(internalShapes, 2)
console.log(`Actual narrative drafts: ${publicShapes} three-year Content schemas passed; ${internalShapes} technical-horizon drafts stayed internal. References passed. Max sampled three-year content: ${maxProductBytes} UTF-8 bytes. Not persistence or paid-quality acceptance.`)
